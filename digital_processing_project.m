function digital_processing_project
freq = 20;
fs = 44100;
len = 1.0;
bits = 16;
amp = 0.5;
% Create a UI figure window
fig = uifigure('Name', 'Digital Processing Project', ...
    'Position', [100 100 900 600]);

lblPanel = uipanel(fig, 'Position', [0 200 120 400], 'BackgroundColor', 'black');
sliderPanel = uipanel(fig, 'Position', [120 200 750 400], 'BackgroundColor', 'black');

lblgrid = uigridlayout(lblPanel, [5 1]);
slidergrid = uigridlayout(sliderPanel, [4 1]);

frequencyLbl = uilabel(lblgrid, ...
    'Text', sprintf('Frequency:\n %.1f', freq), ...
    'Position', [0 750 120 30], ...
    'WordWrap', 'on', ...
    'FontSize', 14);

samplingFrequencyLbl = uilabel(lblgrid, ...
    'Text', sprintf('Sample Freq:\n %.1f', fs), ...
    'FontSize', 14);

bitsLbl = uilabel(lblgrid, ...
    'Text', sprintf('Bits Per Sample:\n %i', bits), ...
    'Position', [150 180 150 30], ...
    'WordWrap', 'on', ...
    'FontSize', 14);

lengthLbl = uilabel(lblgrid, ...
    'Text', sprintf('Length:\n %.1f', len), ...
    'FontSize', 14);

ampLbl = uilabel(lblgrid, ...
    'Text', sprintf('Amplitude:\n %.1f', amp), ...
    'FontSize', 14);

waveTypeLbl = uilabel(lblgrid, ...
    'Text', sprintf('Wave Type:'), ...
    'FontSize', 14);

frequencySlider = uislider(slidergrid, ...
    'Position', [150 100 100 1], ...
    'Limits', [log10(20), log10(10000)], ...
    'Value', log10(freq), ...
    'MajorTicks', log10([20 50 100 200 500 1000 2000 5000 10000]), ...
    'MajorTickLabels', {'20', '50', '100', '200', '500', '1k', '2k', '5k', '10k'});

samplingFrequencySlider = uislider(slidergrid, ...
    'Position', [150 60 100 1], ...
    'limits', [100 44100], ...
    'MajorTicks', [100 4100 12300 20500 28700 36900 44100], ...
    'MajorTickLabels', {'100', '4100', '12300', '20500', '28700', '36900', '44100'}, ...
    'Value', fs);

bitsSlider = uislider(slidergrid, ...
    'Position', [150 20 100 1], ...
    'limits', [3 16], ...
    'Step', 1, ...
    'Value', bits);

lengthSlider = uislider(slidergrid, ...
    'Position', [150 -20 100 1], ...
    'limits', [1 10], ...
    'Step', 0.01, ...
    'Value', len);

ampSlider = uislider(slidergrid, ...
    'Position', [150 -20 100 1], ...
    'limits', [0 1], ...
    'Step', 0.1, ...
    'Value', amp);

wavetypeDropdown = uidropdown(slidergrid, ...
    'Position', [280 125 130 30], ...
    'Items', {'Sine', 'Square', 'Sawtooth'}, ...
    'Value', 'Sine', ...
    'FontSize', 14);

playSoundButton = uibutton(fig, 'push', ...
    'Text', 'Play Sound', ...
    'Position', [150 120 100 40], ...
    'FontSize', 14);

downloadSoundButton = uibutton(fig, 'push', ...
    'Text', 'Download Sound', ...
    'Position', [280 120 150 40], ...
    'FontSize', 14);

% Link slider movement to a callback function
frequencySlider.ValueChangingFcn = @(src, event) updateFreq(src, event, frequencyLbl);

samplingFrequencySlider.ValueChangingFcn = @(src, event) updatefs(src, event, samplingFrequencyLbl);

bitsSlider.ValueChangingFcn = @(src, event) updatebits(src, event, bitsLbl);

lengthSlider.ValueChangingFcn = @(src, event) updateLen(src, event, lengthLbl);

ampSlider.ValueChangingFcn = @(src, event) updateAmp(src, event, ampLbl);

% Assign callback function to button
playSoundButton.ButtonPushedFcn = @(src, event) playSound( ...
    (10 ^ frequencySlider.Value), ...
    lengthSlider.Value, ...
    ampSlider.Value, ...
    bitsSlider.Value, ...
    samplingFrequencySlider.Value, ...
    wavetypeDropdown.Value);

downloadSoundButton.ButtonPushedFcn = @(src, event) downloadSound( ...
    (10 ^ frequencySlider.Value), ...
    lengthSlider.Value, ...
    ampSlider.Value, ...
    bitsSlider.Value, ...
    samplingFrequencySlider.Value, ...
    wavetypeDropdown.Value);
end

function updateFreq(~, event, label)
currentVal = (10 ^ event.Value);
label.Text = sprintf("Frequency:\n %.1f", currentVal);
end

function updateLen(~, event, label)
currentVal = event.Value;
label.Text = sprintf("Length:\n %.1f", currentVal);
end

function updateAmp(~, event, label)
currentVal = event.Value;
label.Text = sprintf("Amplitude:\n %.1f", currentVal);
end

function updatebits(~, event, label)
currentVal = round(event.Value);
label.Text = sprintf("Bits per Sample:\n %i", currentVal);
end

function updatefs(~, event, label)
currentVal = event.Value;
label.Text = sprintf("sampling frequency:\n %.1f", currentVal);
end

% Callback function for button press
function playSound(freq, len, amp, bits, fs, waveType)

finalSound = makeSound(freq, len, amp, bits, fs, waveType);

sound(finalSound, fs);
end

function downloadSound(freq, len, amp, bits, fs, waveType)

finalSound = makeSound(freq, len, amp, bits, fs, waveType);

audiowrite('sound.wav', finalSound, fs, 'BitsPerSample', bits);
end

function resultSound = makeSound(freq, len, amp, bits, fs, waveType)
t = 0:1/fs:len; 

switch waveType
    case 'Sine'
        tone = sin(2 * pi * freq * t);

    case 'Square'
    
        tone = square(2*pi*freq*t);

    case 'Sawtooth'
        tone = sawtooth(2*pi*freq*t);
end

tone = tanh(3 * tone) / tanh(3);

tone = tone * amp;

n = min(round(0.025 * fs), floor(length(tone)/2)); % Fade length (100 samples, safe for short tones)
fade_in  = linspace(0, 1, n);
fade_out = linspace(1, 0, n);

tone(1:n) = tone(1:n) .* fade_in;
tone(end-n+1:end) = tone(end-n+1:end) .* fade_out;

tone = round(tone * (2^(bits-1))) / (2^(bits-1));

resultSound = tone;
end